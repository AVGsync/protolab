func TestBuildIsDeterministic(t *testing.T) {
	a, b := Build(Options{}), Build(Options{})
	if !reflect.DeepEqual(a, b) {
		t.Fatal("two builds differ")
	}
	if len(a.Captures) != 3 || len(a.Versions) != 3 || len(a.Hypotheses) == 0 || len(a.Observations) == 0 {
		t.Fatalf("incomplete dataset: %d captures, %d versions, %d hypotheses, %d observations",
			len(a.Captures), len(a.Versions), len(a.Hypotheses), len(a.Observations))
	}
}

func TestHypothesisIDsAreMapped(t *testing.T) {
	ds := Build(Options{HypothesisID: func(seed string) string { return "hyp-" + seed }})
	for i, v := range ds.Versions {
		raw, err := json.Marshal(v.Spec)
		if err != nil {
			t.Fatal(err)
		}
		if n, mapped := strings.Count(string(raw), `"h-0`), strings.Count(string(raw), `"hyp-h-0`); n != 0 || mapped == 0 {
			t.Errorf("v%d: %d unmapped and %d mapped hypothesis references", i+1, n, mapped)
		}
	}
}

func TestVersionsAreValid(t *testing.T) {
	ds := Build(Options{})
	hashes := map[string]bool{}
	for i, v := range ds.Versions {
		for _, is := range spec.Validate(&v.Spec) {
			if is.Severity == "error" {
				t.Errorf("v%d: %s: %s", i+1, is.Path, is.Message)
			}
		}
		hashes[spec.Hash(&v.Spec)] = true
		if i > 0 && v.CreatedAt <= ds.Versions[i-1].CreatedAt {
			t.Errorf("v%d is not newer than v%d", i+1, i)
		}
	}
	if len(hashes) != len(ds.Versions) {
		t.Error("versions must differ")
	}
}

// reference is the part of the frontend mock data (generated by the TS
// fixtures, see internal/engine/reference_test.go) the demo is a port of.
type reference struct {
	Specs    map[string]json.RawMessage `json:"specs"`
	Sessions []struct {
		Session model.TcpSession `json:"session"`
		Streams []struct {
			Bytes string            `json:"bytes"`
			Gaps  []model.StreamGap `json:"gaps"`
		} `json:"streams"`
	} `json:"sessions"`
}

func loadReference(t *testing.T) reference {
	t.Helper()
	f, err := os.Open("../engine/testdata/reference.json.gz")
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()
	zr, err := gzip.NewReader(f)
	if err != nil {
		t.Fatal(err)
	}
	var ref reference
	if err := json.NewDecoder(zr).Decode(&ref); err != nil {
		t.Fatal(err)
	}
	return ref
}

func TestVersionsMatchFrontendFixtures(t *testing.T) {
	ref := loadReference(t)
	for i, v := range Build(Options{}).Versions {
		name := []string{"v1", "v2", "v3"}[i]
		want, err := spec.Decode(ref.Specs[name])
		if err != nil {
			t.Fatalf("%s: %v", name, err)
		}
		if spec.Hash(&v.Spec) != spec.Hash(want) {
			got, _ := json.Marshal(v.Spec)
			exp, _ := json.Marshal(want)
			t.Errorf("%s differs from the fixture:\n got %s\nwant %s", name, got, exp)
		}
	}
}

// reassembled reads a generated capture the way the importer does.
type reassembled struct {
	format      pcap.Format
	snapLen     uint32
	packets     int
	decodeCodes map[string]int
	sessions    []*tcpflow.Session
}

func reassemble(t *testing.T, c Capture) reassembled {
	t.Helper()
	r, err := pcap.NewReader(bytes.NewReader(c.Data))
	if err != nil {
		t.Fatalf("%s: %v", c.FileName, err)
	}
	out := reassembled{format: r.Format(), decodeCodes: map[string]int{}}
	asm := tcpflow.NewAssembler(tcpflow.Options{OverlapPolicy: tcpflow.PolicyFirst, TargetPorts: []int{devicePort}})
	var last time.Time
	for {
		pkt, err := r.Next()
		if errors.Is(err, io.EOF) {
			break
		}
		if err != nil {
			t.Fatalf("%s: %v", c.FileName, err)
		}
		out.packets++
		if pkt.Timestamp.Before(last) {
			t.Errorf("%s: packet %d goes back in time", c.FileName, pkt.Number)
		}
		last = pkt.Timestamp
		seg, err := netpkt.Decode(pkt.LinkType, pkt.Data, pkt.OrigLen)
		if err != nil {
			var de *netpkt.DecodeError
			if !errors.As(err, &de) {
				t.Fatalf("%s: packet %d: %v", c.FileName, pkt.Number, err)
			}
			out.decodeCodes[de.Code]++
			continue
		}
		asm.Add(tcpflow.Input{Number: pkt.Number, Timestamp: pkt.Timestamp, Seg: seg})
	}
	out.snapLen = r.Interfaces()[0].SnapLen
	out.sessions = asm.Finish()
	return out
}

func TestCapturesHaveTheDeclaredFormat(t *testing.T) {
	ds := Build(Options{})
	want := []struct {
		format  pcap.Format
		snapLen uint32
		codes   map[string]int
	}{
		{pcap.FormatPcapNG, 262144, map[string]int{netpkt.CodeNotIP: 2, netpkt.CodeNotTCP: 3, netpkt.CodeIPv6: 1}},
		{pcap.FormatPcapNG, 262144, map[string]int{}},
		{pcap.FormatPcap, 96, map[string]int{}},
	}
	for i, c := range ds.Captures {
		got := reassemble(t, c)
		if got.format != want[i].format || got.snapLen != want[i].snapLen {
			t.Errorf("%s: %s, snaplen %d", c.FileName, got.format, got.snapLen)
		}
		// Background frames are skipped with a diagnostic, never as malformed.
		if !reflect.DeepEqual(got.decodeCodes, want[i].codes) {
			t.Errorf("%s: frames skipped by the decoder: %v, want %v", c.FileName, got.decodeCodes, want[i].codes)
		}
	}
}

// The reassembled streams must be the ones of the frontend fixtures: the
// same bytes, the same unknown ranges.
func TestCapturesMatchFrontendFixtures(t *testing.T) {
	ref := loadReference(t)
	ds := Build(Options{})
	for ci, c := range ds.Captures {
		got := reassemble(t, c)
		prefix := "ses-" + string(rune('1'+ci)) + "-"
		var want []int
		for i, s := range ref.Sessions {
			if strings.HasPrefix(s.Session.ID, prefix) {
				want = append(want, i)
			}
		}
		// The fixtures number sessions in scenario order, tcpflow by the first packet.
		slices.SortStableFunc(want, func(a, b int) int {
			return strings.Compare(ref.Sessions[a].Session.StartedAt, ref.Sessions[b].Session.StartedAt)
		})
		if len(got.sessions) != len(want) {
			t.Fatalf("%s: %d sessions, want %d", c.FileName, len(got.sessions), len(want))
		}
		for k, s := range got.sessions {
			r := ref.Sessions[want[k]]
			name := c.FileName + " " + r.Session.ID
			if s.Client.String() != addr(r.Session.Client) || s.Server.String() != addr(r.Session.Server) {
				t.Errorf("%s: %v → %v, want %v → %v", name, s.Client, s.Server, r.Session.Client, r.Session.Server)
				continue
			}
			if s.Handshake != r.Session.Flags.Handshake || s.Closed != r.Session.Flags.Closed || s.Status != r.Session.Status {
				t.Errorf("%s: handshake %v closed %v status %s, want %v %v %s", name, s.Handshake, s.Closed, s.Status,
					r.Session.Flags.Handshake, r.Session.Flags.Closed, r.Session.Status)
			}
			for d, st := range s.Streams {
				data, err := base64.StdEncoding.DecodeString(r.Streams[d].Bytes)
				if err != nil {
					t.Fatal(err)
				}
				if !bytes.Equal(st.Data, data) {
					t.Errorf("%s %s: stream bytes differ", name, st.Dir)
				}
				gaps := []model.StreamGap{}
				for _, g := range st.Gaps {
					gaps = append(gaps, model.StreamGap{Offset: g.Offset, Length: g.Length, Reason: g.Reason})
				}
				if !reflect.DeepEqual(gaps, r.Streams[d].Gaps) {
					t.Errorf("%s %s: gaps %+v, want %+v", name, st.Dir, gaps, r.Streams[d].Gaps)
				}
			}
		}
	}
}

func addr(e model.Endpoint) string { return e.IP + ":" + strconv.Itoa(e.Port) }
